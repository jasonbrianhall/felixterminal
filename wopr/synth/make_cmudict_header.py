#!/usr/bin/env python3
"""Pack CMUdict into a C header for Felix Terminal's WOPR voice.

  python3 make_cmudict_header.py cmudict-0.7b cmudict_z.h

Keeps each word's main pronunciation (drops comments and WORD(1)-style
alternates, as synth.c does), zlib-compresses the text and stores it as
base64 in short string literals (MSVC limits the length of one literal).
wopr_speech.cpp decodes it with miniz's mz_uncompress at start-up."""
import base64
import sys
import zlib


def main(src, dst):
    lines = []
    with open(src, encoding='latin-1') as f:
        for line in f:
            if line.startswith(';;;'):
                continue
            word, _, phones = line.rstrip('\r\n').partition('  ')
            if not phones or '(' in word:
                continue
            lines.append(word + '  ' + phones)
    raw = ('\n'.join(lines) + '\n').encode('latin-1')
    z = zlib.compress(raw, 9)
    b64 = base64.b64encode(z).decode('ascii')
    chunks = [b64[i:i + 76] for i in range(0, len(b64), 76)]
    with open(dst, 'w', newline='\n') as out:
        out.write('/* Generated by make_cmudict_header.py from %s: do not edit.\n' % src.split('/')[-1])
        out.write(' * CMUdict (BSD-style licence, Carnegie Mellon University), %d words,\n' % len(lines))
        out.write(' * zlib-compressed and base64-encoded. */\n')
        out.write('#ifndef CMUDICT_Z_H\n#define CMUDICT_Z_H\n\n')
        out.write('static const unsigned long CMUDICT_Z_RAW_SIZE = %dUL;   /* text */\n' % len(raw))
        out.write('static const unsigned long CMUDICT_Z_SIZE     = %dUL;   /* zlib */\n' % len(z))
        out.write('static const int CMUDICT_Z_B64_LINES = %d;\n' % len(chunks))
        out.write('static const char *const CMUDICT_Z_B64[] = {\n')
        for c in chunks:
            out.write('    "%s",\n' % c)
        out.write('};\n\n#endif /* CMUDICT_Z_H */\n')
    print('%s: %d words, %d bytes text, %d compressed, %d base64' % (dst, len(lines), len(raw), len(z), len(b64)))


if __name__ == '__main__':
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
